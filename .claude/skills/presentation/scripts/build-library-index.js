#!/usr/bin/env node

/**
 * Rebuilds library/index.md (for planning) and library/index.html (for browsing) from the
 * COMPONENT comments in library/<folder>/slides.html. The slide files are the only source;
 * never edit the two index files by hand. No dependencies.
 *
 * Usage: node build-library-index.js
 */

const fs = require('fs');
const path = require('path');

const LIBRARY = path.join(__dirname, '..', 'library');
const GROUP_RE = /<!-- GROUP: (\w+) · (.*?) · (.*?) -->/;
const COMPONENT_RE = /<!-- COMPONENT: ([A-Z]+-\d+) · ([\w-]+)\s+Looks like: (.*?)\s+Good for: (.*?)\s+Related: (.*?) -->\s*<section\b([^>]*)>/gs;

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function readGroups() {
  const groups = [];
  const problems = [];
  fs.readdirSync(LIBRARY, { withFileTypes: true }).filter(d => d.isDirectory()).forEach(dir => {
    const file = path.join(LIBRARY, dir.name, 'slides.html');
    if (!fs.existsSync(file)) return;
    const html = fs.readFileSync(file, 'utf8');
    const slides = html.slice(html.indexOf('<!-- SLIDES:START -->'), html.indexOf('<!-- SLIDES:END -->'));
    const g = slides.match(GROUP_RE);
    if (!g) { problems.push(`${dir.name}: no <!-- GROUP: ... --> comment`); return; }
    const group = { folder: dir.name, prefix: g[1], title: g[2], blurb: g[3], components: [] };
    for (const m of slides.matchAll(COMPONENT_RE)) {
      const [, code, name, look, good, related, attrs] = m;
      const id = (attrs.match(/\bid="([^"]+)"/) || [])[1];
      const attrCode = (attrs.match(/data-component="([^"]+)"/) || [])[1];
      if (id !== name) problems.push(`${code}: comment names "${name}" but the section id is "${id}"`);
      if (attrCode !== code) problems.push(`${code}: data-component is "${attrCode}"`);
      if (!code.startsWith(group.prefix + '-')) problems.push(`${code}: prefix does not match its group (${group.prefix})`);
      const goodFor = good.split(';').map(s => s.trim()).filter(Boolean);
      if (goodFor.length < 2 || goodFor.length > 3) problems.push(`${code}: "Good for" needs 2 or 3 items, has ${goodFor.length}`);
      group.components.push({
        code, name, look: look.trim(), goodFor,
        related: related.trim() === 'none' ? [] : related.split(',').map(s => s.trim().split(/\s+/)[0]),
      });
    }
    const sections = (slides.match(/<section\b/g) || []).length;
    if (sections !== group.components.length) problems.push(`${dir.name}: ${sections} slides but ${group.components.length} COMPONENT comments`);
    groups.push(group);
  });
  return { groups, problems };
}

function main() {
  const { groups, problems } = readGroups();
  const order = ['FR', 'EX', 'LV', 'CH', 'CP', 'BD', 'UN', 'DE', 'BK'];
  groups.sort((a, b) => (order.indexOf(a.prefix) + 99) % 99 - (order.indexOf(b.prefix) + 99) % 99 || a.prefix.localeCompare(b.prefix));

  const byCode = {};
  groups.forEach(g => g.components.forEach(c => {
    if (byCode[c.code]) problems.push(`${c.code}: used twice`);
    byCode[c.code] = { ...c, folder: g.folder };
  }));
  const names = {};
  Object.values(byCode).forEach(c => {
    if (names[c.name]) problems.push(`"${c.name}": name used by ${names[c.name]} and ${c.code}`);
    names[c.name] = c.code;
    c.related.forEach(r => { if (!byCode[r]) problems.push(`${c.code}: related component ${r} does not exist`); });
  });

  // index.md
  const md = ['# Slide library', '',
    'Sample slides (components) grouped by what a slide has to do. Planning reads this page only; the slide files are the builder\'s.', '',
    '- Pick by the "Good for" column, not by subject. The samples\' subject matter is placeholder.',
    '- Plan\'s Pattern line: the code and the link, `<code> library/<folder>/slides.html#/<name>`.',
    '- "Related" lists components with a similar visual; check them before settling.',
    '- To browse: open `library/index.html` in a browser. To add one: `references/new-component.md`.',
    '- Generated by `scripts/build-library-index.js` from the slide files. Do not edit by hand.', ''];
  groups.forEach(g => {
    md.push(`## ${g.title}`, '', `${g.blurb} Folder: \`${g.folder}\``, '', '| Code | Name | Looks like | Good for | Related |', '| --- | --- | --- | --- | --- |');
    g.components.forEach(c => {
      md.push(`| ${c.code} | \`${c.name}\` | ${c.look} | ${c.goodFor.map(x => '• ' + x).join('<br>')} | ${c.related.join(', ') || '-'} |`);
    });
    md.push('');
  });
  fs.writeFileSync(path.join(LIBRARY, 'index.md'), md.join('\n'));

  // index.html
  const cards = groups.map(g => `<h2 id="${esc(g.folder)}">${esc(g.title)}</h2><p class="blurb">${esc(g.blurb)}</p><div class="grid">` +
    g.components.map(c => {
      const related = c.related.filter(r => byCode[r]).map(r => `<a href="#${esc(byCode[r].name)}">${esc(r)}</a>`).join(' ');
      return `<div class="item" id="${esc(c.name)}"><a class="open" href="${esc(g.folder)}/slides.html#/${esc(c.name)}">` +
        `<span class="code">${esc(c.code)}</span><h3>${esc(c.name)}</h3></a>` +
        `<p class="look">${esc(c.look)}</p><ul>${c.goodFor.map(x => `<li>${esc(x)}</li>`).join('')}</ul>` +
        (related ? `<p class="related">Related: ${related}</p>` : '') + '</div>';
    }).join('\n') + '</div>').join('\n');
  const nav = groups.map(g => `<a href="#${esc(g.folder)}">${esc(g.title)}</a>`).join('');
  const total = Object.keys(byCode).length;
  fs.writeFileSync(path.join(LIBRARY, 'index.html'), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Slide library</title>
<style>
  html { scroll-behavior: smooth; scroll-padding-top: 70px; }
  body { font-family: "Segoe UI", system-ui, sans-serif; color: #14233a; background: #f4f7fb; margin: 0; }
  nav { position: sticky; top: 0; background: #ffffff; border-bottom: 1px solid #dfe6ef; padding: 12px 28px; display: flex; flex-wrap: wrap; gap: 6px 18px; z-index: 2; }
  nav a { font-size: 13px; color: #44546a; text-decoration: none; } nav a:hover { color: #1c5cab; }
  main { max-width: 1180px; margin: 0 auto; padding: 32px 28px 80px; }
  h1 { font-size: 30px; margin: 0 0 6px; } .intro { color: #44546a; margin: 0 0 8px; max-width: 780px; }
  h2 { font-size: 20px; margin: 44px 0 2px; padding-top: 22px; border-top: 1px solid #dfe6ef; } .blurb { color: #6b7a8f; margin: 0 0 16px; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(330px, 1fr)); gap: 16px; }
  .item { background: #fff; border: 1px solid #dfe6ef; border-radius: 12px; padding: 18px 20px; }
  .item:target { border-color: #1c5cab; box-shadow: 0 0 0 3px #e8f0fb; }
  .open { display: flex; align-items: baseline; gap: 10px; text-decoration: none; }
  .open:hover h3 { text-decoration: underline; }
  .code { font: 600 12px Consolas, monospace; color: #1c5cab; background: #e8f0fb; padding: 3px 8px; border-radius: 99px; white-space: nowrap; }
  .item h3 { font-size: 15px; margin: 0 0 8px; color: #14233a; font-weight: 600; }
  .look { font-size: 14px; color: #44546a; margin: 0 0 10px; } ul { margin: 0; padding-left: 18px; } li { font-size: 14px; margin-bottom: 4px; }
  .related { font-size: 12.5px; color: #6b7a8f; margin: 12px 0 0; } .related a { font-family: Consolas, monospace; color: #1c5cab; text-decoration: none; margin-left: 4px; }
</style></head><body>
<nav>${nav}</nav>
<main>
<h1>Slide library</h1>
<p class="intro">${total} sample slides grouped by what a slide has to do. Click a name to open the slide; "Library index" on the slide brings you back here. The subject matter in each sample is placeholder; the pattern is what gets reused.</p>
${cards}
</main></body></html>
`);

  console.log(`${total} components in ${groups.length} groups. Wrote library/index.md and library/index.html.`);
  if (problems.length) {
    console.log(`\n${problems.length} to fix:`);
    problems.forEach(p => console.log('  - ' + p));
    process.exit(1);
  }
}

main();
